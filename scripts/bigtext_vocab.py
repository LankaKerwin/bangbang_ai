# 合并全集（给 matcher 用）
ALL_BIGTEXT = EVENT_NAMES + FIXED_ANNOUNCE + BOSS_NAMES


def match(name_hyp, candidates=None):
    """判断识别出的文字属于哪个词（包含式，容错空白/叹号等装饰）"""
    import re
    text = re.sub(r"[\s!！。·、,，\-—~～]", "", name_hyp)
    for cand in (candidates or ALL_BIGTEXT):
        if cand in text or text in cand:
            return cand
    return None


